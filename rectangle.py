def area(a, b):
    """
    Вычисляет площадь прямоугольника.

    :param a: длина
    :param b: ширина
    :return: площадь прямоугольника (a * b)

    Пример вызова:
        area(2, 3)  # 6
    """
    return a * b

def perimeter(a, b):
    """
    Вычисляет периметр прямоугольника.

    :param a: длина
    :param b: ширина
    :return: периметр прямоугольника (2 * (a + b))

    Пример вызова:
        perimeter(2, 3)  # 10
    """
    return 2*(a + b)