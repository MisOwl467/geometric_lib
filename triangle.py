def area(a, h):
   """
    Вычисляет площадь треугольника по основанию и высоте.

    :param a: основание
    :param h: высота, опущенная на основание
    :return: площадь треугольника (a * h / 2)

    Пример вызова:
        area(4, 3)  # 6.0
    """
   return a * h / 2
 
def perimeter(a, b, c):
   """
    Вычисляет периметр треугольника.

    :param a: первая сторона
    :param b: вторая сторона
    :param c: третья сторона
    :return: периметр треугольника (a + b + c)

    Пример вызова:
        perimeter(3, 4, 5)  # 12
    """
   return a + b + c