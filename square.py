
def area(a):
    """
    Вычисляет площадь квадрата.

    :param a: длина стороны
    :return: площадь квадрата (a^2)

    Пример вызова:
        area(3)  # 9
    """
    return a * a


def perimeter(a):
    """
    Вычисляет периметр квадрата.

    :param a: длина стороны
    :return: периметр квадрата (4 * a)

    Пример вызова:
        perimeter(3)  # 12
    """
    return 4 * a
